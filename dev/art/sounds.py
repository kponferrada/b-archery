"""Jamie's Crossbows - the crossbows' own sounds, made here from
plain maths (no recordings, nothing copied): short mono 22.05 kHz WAV files, the
format other 42.21 mods load with `clip { file = media/sound/....wav }`.

  JC_CrossbowShoot    the string let go: a deep thump and a short twang
  JC_CrossbowLoad     a bolt slid onto the rail: a soft scrape and a click
  JC_CrossbowCock     the string drawn back: a few ratchet clicks and the latch
  JC_CrossbowDryFire  pulling the trigger with no bolt: one dull click
"""
import math
import struct
import wave

import numpy as np

RATE = 22050


def _env(n, attack, decay):
    t = np.arange(n) / RATE
    a = np.clip(t / max(attack, 1e-4), 0, 1)
    return a * np.exp(-t / decay)


def _click(n, freq, decay, rng, noise=0.6):
    t = np.arange(n) / RATE
    tone = np.sin(TAU * freq * t) * (1 - noise) + rng.normal(0, 1, n) * noise
    return tone * _env(n, 0.0005, decay)


TAU = 2 * math.pi


def shoot(rng):
    n = int(RATE * 0.45)
    t = np.arange(n) / RATE
    thump = np.sin(TAU * (95 - 40 * t) * t) * _env(n, 0.002, 0.06) * 0.9
    twang = sum(np.sin(TAU * f * t) / (k + 1) for k, f in enumerate((210, 420, 655, 880))) * _env(n, 0.001, 0.09) * 0.5
    snap = rng.normal(0, 1, n) * _env(n, 0.0003, 0.008) * 0.6
    whoosh = np.convolve(rng.normal(0, 1, n), np.ones(30) / 30, mode="same") * _env(n, 0.02, 0.12) * 0.5
    return thump + twang + snap + whoosh


def load(rng):
    n = int(RATE * 0.40)
    out = np.zeros(n)
    scrape_n = int(RATE * 0.22)
    scrape = np.convolve(rng.normal(0, 1, scrape_n), np.ones(6) / 6, mode="same") * np.hanning(scrape_n) * 0.35
    out[:scrape_n] += scrape
    c0 = int(RATE * 0.25)
    m = n - c0
    out[c0:] += _click(m, 1800, 0.012, rng) * 0.9
    return out


def cock(rng):
    n = int(RATE * 0.65)
    out = np.zeros(n)
    for k in range(4):
        at = int(RATE * (0.04 + 0.09 * k))
        m = int(RATE * 0.05)
        out[at:at + m] += _click(m, 2400 + 150 * k, 0.006, rng) * 0.5
    at = int(RATE * 0.48)
    m = n - at
    out[at:] += _click(m, 900, 0.03, rng, noise=0.4) * 1.0
    return out


def dry(rng):
    n = int(RATE * 0.15)
    return _click(n, 700, 0.02, rng, noise=0.5) * 0.8


SOUNDS = {"JC_CrossbowShoot": shoot, "JC_CrossbowLoad": load, "JC_CrossbowCock": cock, "JC_CrossbowDryFire": dry}
# (category, distanceMax in tiles, volume): what players hear; zombies hear the item's SoundRadius
SOUND_SCRIPT = {"JC_CrossbowShoot": ("Item", 20, 0.9), "JC_CrossbowLoad": ("Item", 8, 0.6),
                "JC_CrossbowCock": ("Item", 8, 0.7), "JC_CrossbowDryFire": ("Item", 6, 0.6)}


def write_wav(path, x):
    x = np.asarray(x, dtype=float)
    peak = np.max(np.abs(x)) or 1.0
    x = x / peak * 0.85
    pcm = (np.clip(x, -1, 1) * 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(pcm.tobytes())


def write_all(sound_dir, seed=42):
    """Writes the WAVs into sound_dir and returns the sound script text."""
    import os
    os.makedirs(sound_dir, exist_ok=True)
    rng = np.random.default_rng(seed)
    blocks = []
    for name, fn in SOUNDS.items():
        write_wav(os.path.join(sound_dir, name + ".wav"), fn(rng))
        cat, dist, vol = SOUND_SCRIPT[name]
        blocks.append("""    sound %s
    {
        category = %s,
        clip
        {
            file = media/sound/JamiesCrossbows/%s.wav,
            distanceMax = %d,
            volume = %s,
        }
    }
""" % (name, cat, name, dist, vol))
    return ("/* Jamie's Crossbows - sounds. GENERATED by dev/build.py (dev/art/sounds.py). */\n"
            "module JamiesCrossbows\n{\n%s}\n" % "\n".join(blocks))
